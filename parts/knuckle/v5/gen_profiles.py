"""Generate the smoothed silhouette profiles used by knuckle.py (data only, like pedal_sections.py).
For each named box, project the scan triangles inside the box along X, Y and Z, clean the raster
(closing/opening), trace contours, low-pass them, and snap round contours to exact circles."""
