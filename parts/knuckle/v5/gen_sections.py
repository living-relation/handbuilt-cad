"""Generate smoothed station sections for the lofted regions of the knuckle (data only)."""
import sys, pprint
sys.path.insert(0, "/workspace/hbwork")
import numpy as np
from hb_common import load_scan_hb
from shapely.geometry import Polygon, box as sbox, MultiPolygon
from shapely.ops import unary_union
from shapely.validation import make_valid

# name: (lo, hi, loft axis, station step)
LOFTS = {   # back web: a few smoothed Y-stations, lofted (replaces the three-view block)
    "back_web": ((-73.3, 40, 37.7), (69.3, 104, 80.4), "y", 8.0),   # lower, sloped part of the web
}
NPTS = 40
COLLAR = (46.0, 39.5, 65.5)   # hub collar radius, z from, z to

def section(s, ax, L, lo, hi, name=""):
    n = np.zeros(3); n[ax] = 1; o = np.zeros(3); o[ax] = L
    p = s.section(plane_origin=o, plane_normal=n)
    if p is None: return None
    a, b = [i for i in range(3) if i != ax]
    rings = []
    for d in p.discrete:
        if len(d) < 4: continue
        q = Polygon(d[:, [a, b]])
        q = q if q.is_valid else make_valid(q).buffer(0)
        if q.area > 0.3: rings.append(q)
    rings.sort(key=lambda q: -q.area)
    g = None
    for q in rings: g = q if g is None else g.symmetric_difference(q)
    if g is None: return None
    g = g.intersection(sbox(lo[a], lo[b], hi[a], hi[b]))
    g = unary_union([q for q in getattr(g, "geoms", [g]) if q.geom_type == "Polygon" and q.area > 2])
    if g.is_empty: return None
    if name == "body" and ax == 1 and abs(L) < COLLAR[0]:          # bridge the hub bore with the hub collar (r<=R, z0..z1); the bore is cut exactly later
        R, z0, z1 = COLLAR; hw = (R * R - L * L) ** 0.5
        g = unary_union([g, sbox(-hw, z0, hw, z1)])
    r = 1.0
    while g.geom_type != "Polygon" and r < 40:
        g = g.buffer(r, join_style=1).buffer(-r, join_style=1); r *= 1.5
    if g.geom_type != "Polygon":
        g = max(g.geoms, key=lambda q: q.area)
    g = Polygon(g.exterior).buffer(4.0).buffer(-4.0).simplify(1.0)   # fill pockets/holes, simplify to straight-ish edges
    return g if g.geom_type == "Polygon" else max(g.geoms, key=lambda q: q.area)

def smooth_ring(g, K):
    from shapely.geometry.polygon import orient
    g = orient(g, 1.0); c = np.asarray(g.exterior.coords)[:-1]
    q = np.vstack([c, c[:1]]); seg = np.linalg.norm(np.diff(q, axis=0), axis=1); s = np.r_[0, np.cumsum(seg)]
    t = np.linspace(0, s[-1], 512, endpoint=False)
    p = np.c_[np.interp(t, s, q[:, 0]), np.interp(t, s, q[:, 1])]
    z = p[:, 0] + 1j * p[:, 1]; F = np.fft.fft(z); F[K + 1:-K] = 0; p = np.fft.ifft(F); p = np.c_[p.real, p.imag]
    # uniform resample, start at the point straight "right" of the centroid (stable seam for lofting)
    q = np.vstack([p, p[:1]]); seg = np.linalg.norm(np.diff(q, axis=0), axis=1); s = np.r_[0, np.cumsum(seg)]
    ctr = p.mean(0); ang = np.arctan2(p[:, 1] - ctr[1], p[:, 0] - ctr[0]); i0 = np.argmin(np.abs(ang))
    t = (s[i0] + np.linspace(0, s[-1], NPTS, endpoint=False)) % s[-1]
    return np.c_[np.interp(t, s, q[:, 0]), np.interp(t, s, q[:, 1])]

if __name__ == "__main__":
    s = load_scan_hb("knuckle", "/workspace/hbwork/knuckle")
    data = {}
    for name, (lo, hi, axn, step) in LOFTS.items():
        ax = "xyz".index(axn); st = []
        for L in np.arange(lo[ax] + 0.5, hi[ax] - 0.49, step).tolist() + [hi[ax] - 0.5]:
            g = section(s, ax, L, lo, hi, name)
            if g is None or g.area < 5: continue
            K = int(np.clip(g.length / 9, 10, 26))
            ring = smooth_ring(g, K)
            if st and name != "body":   # cyclic shift that best matches the previous station (stops the loft from twisting)
                prev = np.asarray(st[-1][1]); pc = prev - prev.mean(0); rc = ring - ring.mean(0)
                k = int(np.argmin([((np.roll(rc, -j, 0) - pc) ** 2).sum() for j in range(NPTS)])); ring = np.roll(ring, -k, 0)
            st.append((round(L, 2), [[round(float(u), 2), round(float(v), 2)] for u, v in ring]))
        data[name] = {"box": [list(lo), list(hi)], "axis": axn, "stations": st}
        print(name, len(st), "stations")
    with open("knuckle_sections.py", "w") as f:
        f.write('"""Smoothed loft stations (generated by gen_sections.py from the scan; do not edit by hand)."""\n')
        f.write("SECTIONS = " + pprint.pformat(data, width=200, compact=True) + "\n")
