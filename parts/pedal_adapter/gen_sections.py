"""Measure smoothed body cross-sections from the scan and write pedal_sections.py.

Each station is a y-plane cut of the scan, clipped to the housing envelope
(x <= X_CLIP, z >= Z_CLIP) so bolt-on features stay out, then low-pass
filtered (Fourier, K harmonics) so scan texture is removed, and pushed
outward by DELTA so the crisp clip planes in pedal_adapter.py own every flat.
"""
from common import *
import trimesh.intersections as TI
from shapely.geometry import MultiLineString, LineString, Polygon, box
from shapely.ops import linemerge, polygonize, unary_union
import json, sys

X_CLIP, Z_CLIP = 39.3, 16.2
CLOSE_R = 4.0   # morphological closing radius: fills pockets/dents narrower than ~8 mm
K, NOUT, DELTA = 14, 40, 0.15
WALL_FILL = 6.0      # fill this far in from the flat right-hand walls before smoothing
def x_wall(y):       # flat right-hand wall at this station (side plates 38.3, recess 35.5)
    return 35.5 if -42.0 < y < -9.0 else 38.3
s = load_scan()

def section_polygon(axis, L):
    a, b = {"y": (0, 2), "z": (0, 1)}[axis]
    k = {"y": 1, "z": 2}[axis]
    nrm = np.zeros(3); nrm[k] = 1; o = np.zeros(3); o[k] = L
    segs = TI.mesh_plane(s, plane_normal=nrm, plane_origin=o)[:, :, [a, b]]
    segs = np.round(segs, 5)
    if len(segs) == 0: return None, False
    merged = linemerge(MultiLineString([tuple(map(tuple, sg)) for sg in segs]))
    lines = list(merged.geoms) if hasattr(merged, "geoms") else [merged]
    lines.sort(key=lambda l: -l.length)
    polys = [p for p in polygonize(lines) if p.area > 50]
    if polys:
        return max(polys, key=lambda p: p.area), True
    if not lines or lines[0].length < 1: return None, False
    main = lines[0]; c = list(main.coords)
    return Polygon(c + [c[0]]).buffer(0), False

def smooth_loop(poly, start_dir=(1.0, 0.0)):
    ext = np.asarray(poly.exterior.coords)[:-1]
    if Polygon(ext).exterior.is_ccw is False: ext = ext[::-1]
    d = np.r_[0, np.cumsum(np.linalg.norm(np.diff(np.vstack([ext, ext[:1]]), axis=0), axis=1))]
    M = 1024; t = np.linspace(0, d[-1], M, endpoint=False)
    closed = np.vstack([ext, ext[:1]])
    xs = np.interp(t, d, closed[:, 0]); zs = np.interp(t, d, closed[:, 1])
    Z = np.fft.fft(xs + 1j * zs); Z[K + 1:M - K] = 0
    c = np.fft.ifft(Z)
    pts = np.c_[c.real, c.imag]
    tang = np.gradient(pts, axis=0); nrm = np.c_[tang[:, 1], -tang[:, 0]]; nrm /= np.linalg.norm(nrm, axis=1)[:, None]
    pts = pts + DELTA * nrm      # outward for CCW loop
    ctr = pts.mean(0); ang = np.arctan2(pts[:, 1] - ctr[1], pts[:, 0] - ctr[0])
    i0 = int(np.argmin(np.abs(ang)))
    pts = np.roll(pts, -i0, axis=0)
    idx = np.linspace(0, M, NOUT, endpoint=False).astype(int)
    return pts[idx]

MOUTH_N = np.array([0.228, 0.936, 0.268]); MOUTH_C = np.array([9.85, -80.52, 33.76])
stations = list(np.arange(20.0, -70.0, -4.0)) + [-72.0, -76.0, -80.0, -84.0, -88.0, -92.0, -95.0]
out = []; prev = None
for y in stations:
    poly, closed = section_polygon("y", y)
    poly = prev if poly is None else poly.intersection(box(-60, Z_CLIP, X_CLIP, 90)).buffer(0)
    if not closed and prev is not None:
        # beyond the scan crop plane there is no data: carry the previous profile forward there
        nx_, ny_, nz_ = MOUTH_N; k0 = MOUTH_N @ MOUTH_C - ny_ * y      # plane: nx*x + nz*z = k0 at this y
        big = 400.0; beyond = Polygon([(-big, (k0 + nx_ * big) / nz_), (big, (k0 - nx_ * big) / nz_), (big, -big), (-big, -big)])
        poly = unary_union([poly, prev.intersection(beyond)]).buffer(0.01).buffer(-0.01)
    if poly.geom_type != "Polygon": poly = max(poly.geoms, key=lambda p: p.area)
    prev = poly
    poly = poly.buffer(CLOSE_R, join_style=1).buffer(-CLOSE_R, join_style=1)
    if poly.geom_type != "Polygon": poly = max(poly.geoms, key=lambda p: p.area)
    xw = x_wall(y); ext = np.asarray(poly.exterior.coords)
    near = ext[ext[:, 0] > xw - 2.0]
    if len(near) > 3:
        poly = unary_union([poly, box(xw - WALL_FILL, near[:, 1].min(), xw + 0.3, near[:, 1].max())]).buffer(0)
        if poly.geom_type != "Polygon": poly = max(poly.geoms, key=lambda p: p.area)
    pts = smooth_loop(poly)
    out.append((float(y), closed, np.round(pts, 2).tolist()))
    print("y", y, "closed" if closed else "OPEN(chord)", "area %.0f" % poly.area, "x %.1f..%.1f z %.1f..%.1f" % (pts[:,0].min(), pts[:,0].max(), pts[:,1].min(), pts[:,1].max()))

# smooth across stations too (1-2-1), keeping the end stations
arr = np.array([o[2] for o in out], float)
sm = arr.copy()   # cross-station smoothing disabled: it twisted the loft
out = [(o[0], o[1], np.round(sm[i], 2).tolist()) for i, o in enumerate(out)]
# plan outline at mid height (z=35), used to trim the plan shape
pp, closed = section_polygon("z", 35.0)
pp = pp.simplify(0.15)
plan = np.asarray(pp.exterior.coords)[:-1]
with open("pedal_sections.py", "w", encoding="utf-8") as f:
    f.write('"""Measured body stations for pedal_adapter.py (generated by gen_sections.py).\n\n'
            'BODY_STATIONS: list of (y_mm, [(x_mm, z_mm), ...]) closed smooth profiles,\n'
            f'closed with r={CLOSE_R} mm, Fourier low-pass K={K}, pushed out {DELTA} mm, clipped x<={X_CLIP}, z>={Z_CLIP}.\n'
            'PLAN_Z35: plan outline (x_mm, y_mm) of the scan cut at z=35, simplified 0.15 mm.\n"""\n')
    f.write("BODY_STATIONS = [\n")
    for y, c, pts in out:
        f.write(f"    ({y}, {[tuple(p) for p in pts]}),\n")
    f.write("]\n")
    f.write(f"PLAN_Z35 = {[tuple(np.round(p, 2).tolist()) for p in plan]}\n")
print("plan pts", len(plan), "closed", closed)






